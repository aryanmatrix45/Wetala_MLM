import { Member } from '../models/Member.model';
import { Package } from '../models/Package.model';
import { Purchase, IPurchase } from '../models/Purchase.model';
import { PURCHASE_STATUS, PURCHASE_TYPE } from '../config/constants';

/** Paid, approved package and product orders: what the company actually sold */
export const PAID_ORDER_FILTER = {
  $or: [
    { status: PURCHASE_STATUS.COMPLETED, paymentStatus: 'PAID' as const },
    { approvalStage: 'VERIFIED_AND_PAID' as const, paymentStatus: 'PAID' as const },
  ],
};

/**
 * Company gross business volume for a period. One calculation shared by the dashboard's Weekly
 * Gross Volume and the welcome bonus settlement, so the two always agree.
 *
 * Each order belongs to the moment it was completed (falling back to verification, then creation),
 * so an order is counted in exactly one week. BV generated by the Super Admin and BV transfers are
 * not sales and are not counted.
 */
export class GrossVolumeService {
  static saleDate(p: Pick<IPurchase, 'completedAt' | 'verifiedAt' | 'createdAt'>): Date {
    return new Date(p.completedAt || p.verifiedAt || p.createdAt);
  }

  static async forPeriod(start: Date, end: Date): Promise<{ bv: number; revenue: number }> {
    const inRange = { $gte: start, $lte: end };
    const [candidates, paidJoiningMemberIds, newMembers] = await Promise.all([
      Purchase.find({
        $and: [PAID_ORDER_FILTER, { $or: [{ completedAt: inRange }, { verifiedAt: inRange }, { createdAt: inRange }] }],
      }).lean(),
      Purchase.distinct('memberId', { $and: [PAID_ORDER_FILTER, { type: PURCHASE_TYPE.JOINING }] }),
      Member.find({ createdAt: inRange, packageBv: { $gt: 0 } }).lean(),
    ]);

    let bv = 0;
    let revenue = 0;
    for (const p of candidates) {
      const date = this.saleDate(p);
      if (date < start || date > end) continue;
      bv += p.totalBV || 0;
      revenue += p.totalAmount || 0;
    }

    // Members given a package directly, without a joining order (e.g. the root member)
    const paidJoining = new Set(paidJoiningMemberIds);
    const directPackages = newMembers.filter((m) => !paidJoining.has(m.memberId));
    if (directPackages.length > 0) {
      const packages = await Package.find().lean();
      const priceOf = (key: string) =>
        packages.find((pkg) => [pkg.packageId, pkg.name, pkg.badge].some((k) => (k || '').toLowerCase().trim() === key))?.price || 0;
      for (const m of directPackages) {
        bv += m.packageBv || 0;
        revenue += priceOf((m.joiningPackageId || m.packageName || '').toLowerCase().trim());
      }
    }

    return { bv, revenue };
  }
}

export default GrossVolumeService;
